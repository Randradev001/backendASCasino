SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRANSACTION;

IF NOT EXISTS (
  SELECT 1 FROM dbo.PROGRAM
  WHERE SistCod=55 AND Modcod=1 AND ProgCod=91
)
  THROW 51000, 'No existe el programa 55/1/91.', 1;

IF NOT EXISTS (SELECT 1 FROM dbo.UROLES WHERE RTRIM(ROLCod)='CAS_USER')
  THROW 51001, 'No existe el rol CAS_USER.', 1;

IF NOT EXISTS (
  SELECT 1 FROM dbo.ASIGPROG
  WHERE GECODEMP=0 AND RTRIM(UsuLogin)='CAS_USER'
    AND SistCod=55 AND Modcod=1 AND ProgCod=91
)
  INSERT dbo.ASIGPROG(GECODEMP,UsuLogin,SistCod,Modcod,ProgCod,ProgUsuC)
  VALUES(0,'CAS_USER',55,1,91,'MIGRACION');

COMMIT TRANSACTION;

SELECT RTRIM(UsuLogin) Rol,SistCod,Modcod,ProgCod
FROM dbo.ASIGPROG
WHERE GECODEMP=0 AND RTRIM(UsuLogin)='CAS_USER'
  AND SistCod=55 AND Modcod=1 AND ProgCod IN (1,91)
ORDER BY ProgCod;
